export type StatusCobranca =
  | "pendente"
  | "em_atraso"
  | "pago"
  | "negociacao"
  | "cancelado";

export interface CobrancaRelacionadaItem {
  id: string;
  nome: string;
  valor: number;
  status: "recebido" | "pendente" | "em_atraso";
  statusRotulo: string;
}

export interface ParcelaCobrancaItem {
  numero: number;
  total: number;
  vencimento: string;
  valor: number;
  status: "pago" | "pendente" | "em_atraso";
  doc?: string;
}

export interface HistoricoCobrancaItem {
  data: string;
  hora: string;
  evento: string;
  tipo: "criado" | "lembrete" | "pagamento" | "status" | "negociacao";
}

export interface CobrancaItem {
  id: string;
  vencimento: string;
  cliente: string;
  clienteSegmento: string;
  clienteLogoLetra: string;
  clienteLogoBg: string;
  descricao: string;
  subtituloContrato: string;
  valor: number;
  valorOriginal: number;
  valorPendente: number;
  dataEmissao: string;
  status: StatusCobranca;
  statusRotulo: "Pendente" | "Em atraso" | "Pago" | "Negociação" | "Cancelada";
  dias: number;
  diasTexto: string;
  origem: "Contrato" | "Proposta" | "Avulso";
  contrato: string;
  formaPagamento: "PIX" | "Boleto" | "Cartão" | "Transferência";
  categoria: string;
  responsavelNome: string;
  cobrancasRelacionadas: CobrancaRelacionadaItem[];
  parcelas: ParcelaCobrancaItem[];
  historico: HistoricoCobrancaItem[];
}

